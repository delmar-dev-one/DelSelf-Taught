public class exercicio01_Comparacao {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        System.out.println(">>> OPERADORES DE COMPARAÇÃO >>>");
        System.out.println("a > b: " + (a > b));
        System.out.println("a == b: " + (a == b));
        System.out.println("a <= b: " + (a <= b));

        System.out.println("\n--- Outros exemplos ---");
        int valorA = 7;
        int valorB = 3;

        System.out.println("valorA == valorB: " + (valorA == valorB));
        System.out.println("valorA != valorB: " + (valorA != valorB));
        System.out.println("valorA < valorB: " + (valorA < valorB));
    }
}
